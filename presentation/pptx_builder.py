"""
PPTX Builder
=============
Builds professional PowerPoint presentations from validated SlideData.
Generates into BytesIO buffer — never writes temp files to disk.
Uses python-pptx for slide creation with a professional theme.
"""

import io
from pptx import Presentation
from pptx.util import Inches, Pt, Emu
from pptx.dml.color import RGBColor
from pptx.enum.text import PP_ALIGN, MSO_ANCHOR
from schemas.slides import SlideData
from utils.helpers import setup_logger

logger = setup_logger(__name__)

# ── Theme Constants ──────────────────────────────────────
NAVY = RGBColor(0x1B, 0x2A, 0x4A)       # Title bar / headers
WHITE = RGBColor(0xFF, 0xFF, 0xFF)       # Title text on navy
DARK_TEXT = RGBColor(0x33, 0x33, 0x33)   # Body text
ACCENT = RGBColor(0x2E, 0x86, 0xAB)     # Accent / bullets
LIGHT_BG = RGBColor(0xF5, 0xF7, 0xFA)   # Slide background
FOOTER_COLOR = RGBColor(0x99, 0x99, 0x99)

SLIDE_WIDTH = Inches(13.333)  # Widescreen 16:9
SLIDE_HEIGHT = Inches(7.5)


def build_presentation(slide_data: SlideData) -> io.BytesIO:
    """Build a professional PPTX from validated SlideData.

    Args:
        slide_data: Pydantic-validated SlideData object.

    Returns:
        BytesIO buffer containing the PPTX file.
    """
    prs = Presentation()
    prs.slide_width = SLIDE_WIDTH
    prs.slide_height = SLIDE_HEIGHT

    # Add title slide
    _add_title_slide(prs, slide_data.paper_title, slide_data.authors)

    # Add content slides
    for slide_content in slide_data.slides:
        _add_content_slide(prs, slide_content.title, slide_content.bullets, slide_content.speaker_notes)

    # Save to BytesIO buffer
    buffer = io.BytesIO()
    prs.save(buffer)
    buffer.seek(0)

    logger.info(f"Built PPTX: {len(slide_data.slides)} content slides + 1 title slide")
    return buffer


def _add_title_slide(prs: Presentation, title: str, authors: str | None):
    """Add a professional title slide with navy background."""
    slide_layout = prs.slide_layouts[6]  # Blank layout
    slide = prs.slides.add_slide(slide_layout)

    # Navy background
    background = slide.background
    fill = background.fill
    fill.solid()
    fill.fore_color.rgb = NAVY

    # Title text
    left = Inches(1)
    top = Inches(2.5)
    width = Inches(11.333)
    height = Inches(2)
    txBox = slide.shapes.add_textbox(left, top, width, height)
    tf = txBox.text_frame
    tf.word_wrap = True
    p = tf.paragraphs[0]
    p.text = title
    p.font.size = Pt(36)
    p.font.bold = True
    p.font.color.rgb = WHITE
    p.alignment = PP_ALIGN.CENTER

    # Authors
    if authors:
        p2 = tf.add_paragraph()
        p2.text = authors
        p2.font.size = Pt(18)
        p2.font.color.rgb = RGBColor(0xBB, 0xCC, 0xDD)
        p2.alignment = PP_ALIGN.CENTER
        p2.space_before = Pt(20)

    # Footer
    _add_footer(slide, "Generated by PaperPilot AI")


def _add_content_slide(prs: Presentation, title: str, bullets: list[str], notes: str | None = None):
    """Add a content slide with title bar and bullet points."""
    slide_layout = prs.slide_layouts[6]  # Blank layout
    slide = prs.slides.add_slide(slide_layout)

    # Light background
    background = slide.background
    fill = background.fill
    fill.solid()
    fill.fore_color.rgb = LIGHT_BG

    # Navy title bar at top
    title_bar = slide.shapes.add_shape(
        1,  # Rectangle
        Inches(0), Inches(0),
        SLIDE_WIDTH, Inches(1.2)
    )
    title_bar.fill.solid()
    title_bar.fill.fore_color.rgb = NAVY
    title_bar.line.fill.background()

    # Title text on bar
    title_box = slide.shapes.add_textbox(
        Inches(0.8), Inches(0.15),
        Inches(11.733), Inches(0.9)
    )
    tf = title_box.text_frame
    tf.word_wrap = True
    p = tf.paragraphs[0]
    p.text = title
    p.font.size = Pt(28)
    p.font.bold = True
    p.font.color.rgb = WHITE
    p.alignment = PP_ALIGN.LEFT

    # Bullet points
    bullet_box = slide.shapes.add_textbox(
        Inches(1), Inches(1.6),
        Inches(11.333), Inches(5.2)
    )
    tf = bullet_box.text_frame
    tf.word_wrap = True

    for i, bullet in enumerate(bullets):
        if i == 0:
            p = tf.paragraphs[0]
        else:
            p = tf.add_paragraph()
        p.text = f"• {bullet}"
        p.font.size = Pt(18)
        p.font.color.rgb = DARK_TEXT
        p.space_before = Pt(12)
        p.space_after = Pt(6)

    # Speaker notes
    if notes:
        notes_slide = slide.notes_slide
        notes_slide.notes_text_frame.text = notes

    # Footer
    _add_footer(slide, "PaperPilot AI")


def _add_footer(slide, text: str):
    """Add a subtle footer to a slide."""
    footer_box = slide.shapes.add_textbox(
        Inches(0.5), Inches(7.0),
        Inches(12.333), Inches(0.3)
    )
    tf = footer_box.text_frame
    p = tf.paragraphs[0]
    p.text = text
    p.font.size = Pt(10)
    p.font.color.rgb = FOOTER_COLOR
    p.alignment = PP_ALIGN.RIGHT
